function write_review_summary(results)
% Summarize measured values from this run for the project review.
m = results.metrics;
reference = results.tests(ismember({results.tests.id},{'T1','T2','T3','T4','T5','T6'}));
referencePassed = numel(reference)==6 && all(strcmp({reference.status},'PASS'));
text = sprintf(['MiR100 navigation review\n' ...
    'Goal: [%.3f, %.3f] m\nStop: %s\nGoal error: %.4f m\n' ...
    'Distance travelled: %.3f m\nSimulated time: %.2f s\n' ...
    'Minimum footprint clearance: %.4f m\nBetween-sample clearance lower bound: %.4f m\n' ...
    'Collision detected: %d\nCore passed: %d\nReference validation passed: %d\n' ...
    'Planner: %s; controller: %s\n' ...
    'Model: %s\nSensing: %s\n' ...
    'Reference tests use their own standard goal; simulation is kinematic.\n'], ...
    results.goal, m.stopReason, m.finalGoalErrorM, m.distanceTravelledM, ...
    m.simTimeS, m.minClearanceM, m.continuousClearanceLowerBoundM, ...
    m.collision, results.corePass, referencePassed, results.algorithms.planner, ...
    results.algorithms.controller, results.algorithms.motionModel, results.algorithms.sensing);
writelines(string(text),fullfile(results.outputDir,'review_summary.txt'));
fprintf('\n%s',text);
end
